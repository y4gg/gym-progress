import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

async function staticAssets(directory, prefix = "/_next/static") {
  const entries = await readdir(directory, { withFileTypes: true });
  const assets = await Promise.all(
    entries.map(async (entry) => {
      const url = `${prefix}/${entry.name}`;
      if (entry.isDirectory())
        return staticAssets(join(directory, entry.name), url);
      return /\.(js|css|woff2?|png|jpe?g|svg|webp|ico)$/.test(entry.name)
        ? [url]
        : [];
    }),
  );
  return assets.flat().sort();
}

const [buildId, worker, assets] = await Promise.all([
  readFile(".next/BUILD_ID", "utf8"),
  readFile("scripts/service-worker.js", "utf8"),
  staticAssets(".next/static"),
]);
// Fail the build if the offline document was not successfully prerendered.
await readFile(".next/server/app/offline.html");
const urls = ["/offline", ...assets];
const version = createHash("sha256")
  .update(buildId)
  .update(worker)
  .update(JSON.stringify(urls))
  .digest("hex")
  .slice(0, 16);
await mkdir("public", { recursive: true });
await writeFile(
  "public/sw.js",
  `// Generated by scripts/generate-service-worker.mjs.\nconst CACHE_NAME = ${JSON.stringify(`gym-ladder-offline-${version}`)};\nconst PRECACHE_URLS = ${JSON.stringify(urls)};\n${worker}`,
);
console.log(
  `Generated offline service worker with ${urls.length} precached files.`,
);
